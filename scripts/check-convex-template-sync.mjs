import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const templateRoot = join(repoRoot, 'packages/cms/templates/convex')
const playgroundRoot = join(repoRoot, 'playground/convex')
const targetRoots = [playgroundRoot, join(repoRoot, 'test/fixtures/basic/convex')]
const rootGeneratedFiles = ['auth.ts', 'convex.config.ts', 'http.ts']
// Better Convex Nuxt owns its component files. Ginko only generates its CMS
// component bridge into the host application.
const generatedDirs = ['ginkoCms']
const ignoredNames = new Set(['_generated'])
const manifestName = '.ginko-cms-setup.json'
const contractBindingPath = 'ginkoCms/contractBinding.ts'
const contentHashToken = '__GINKO_CMS_EXPECTED_CONTENT_HASH__'
const presentationHashToken = '__GINKO_CMS_EXPECTED_PRESENTATION_HASH__'
const validBindingHash = /^(?:unbound|[a-f0-9]{64})$/u
const mcpBlock = /\/\/ GINKO_MCP_BEGIN\n([\s\S]*?)\/\/ GINKO_MCP_END\n?/gu

function toRepoPath(filePath) {
  return relative(repoRoot, filePath).replaceAll('\\', '/')
}

function collectGeneratedFiles(directory, prefix = '') {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (ignoredNames.has(entry.name)) continue
    const relPath = prefix ? `${prefix}/${entry.name}` : entry.name
    const fullPath = join(directory, entry.name)
    if (entry.isDirectory()) {
      files.push(...collectGeneratedFiles(fullPath, relPath))
    } else if (entry.isFile()) {
      files.push(relPath)
    }
  }
  return files
}

function expectedGeneratedSource(relPath, templateSource, targetSource, mcp) {
  if (relPath === 'http.ts') {
    return templateSource.replace(mcpBlock, mcp ? '$1' : '')
  }
  if (relPath !== contractBindingPath) return templateSource
  const contentHash = targetSource.match(/EXPECTED_CONTENT_HASH = '([^']+)'/u)?.[1]
  const presentationHash = targetSource.match(/PRESENTATION_HASH = '([^']+)'/u)?.[1]
  if (!validBindingHash.test(contentHash ?? '') || !validBindingHash.test(presentationHash ?? '')) {
    return templateSource
  }
  return templateSource
    .replace(contentHashToken, contentHash)
    .replace(presentationHashToken, presentationHash)
}

const generatedFiles = [
  ...rootGeneratedFiles,
  ...generatedDirs.flatMap((dir) => collectGeneratedFiles(join(templateRoot, dir), dir)),
].sort()
const manifestFiles = [...new Set([...generatedFiles, 'auth.config.ts', 'schema.ts'])].sort()

const violations = []

for (const targetRoot of targetRoots) {
  const manifestPath = join(targetRoot, manifestName)
  let manifest
  if (!existsSync(manifestPath)) {
    violations.push(`${toRepoPath(manifestPath)}: missing generated setup provenance manifest`)
  } else {
    manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
    if (manifest.schemaVersion !== 1 || manifest.generatedBy !== '@lupinum/ginko-cms') {
      violations.push(`${toRepoPath(manifestPath)}: invalid generated setup provenance manifest`)
      manifest = undefined
    }
  }
  const mcp = manifest?.mcp === true

  for (const relPath of generatedFiles) {
    const templatePath = join(templateRoot, relPath)
    const targetPath = join(targetRoot, relPath)
    if (!existsSync(targetPath)) {
      violations.push(
        `${toRepoPath(targetPath)}: missing generated setup file from ${toRepoPath(templatePath)}`,
      )
      continue
    }
    if (!statSync(targetPath).isFile()) {
      violations.push(
        `${toRepoPath(targetPath)}: expected generated setup file from ${toRepoPath(templatePath)}`,
      )
      continue
    }
    const targetSource = readFileSync(targetPath, 'utf8')
    const templateSource = readFileSync(templatePath, 'utf8')
    if (
      targetRoot === playgroundRoot &&
      relPath === contractBindingPath &&
      /(?:EXPECTED_CONTENT_HASH|PRESENTATION_HASH) = 'unbound'/u.test(targetSource)
    ) {
      violations.push(
        `${toRepoPath(targetPath)}: release playground contract binding must be generated by ginko-cms deploy`,
      )
    }
    const expectedSource = expectedGeneratedSource(relPath, templateSource, targetSource, mcp)
    if (expectedSource !== targetSource) {
      violations.push(
        `${toRepoPath(targetPath)}: differs from generated template ${toRepoPath(templatePath)}`,
      )
    }
  }

  if (!manifest) continue
  for (const relPath of manifestFiles) {
    const targetSource = readFileSync(join(targetRoot, relPath), 'utf8')
    const templateSource = readFileSync(join(templateRoot, relPath), 'utf8')
    const expectedSource = expectedGeneratedSource(relPath, templateSource, targetSource, mcp)
    const expectedHash = createHash('sha256').update(expectedSource).digest('hex')
    const recordedHash = manifest.files?.[`convex/${relPath}`]?.templateHash
    if (recordedHash !== expectedHash) {
      violations.push(
        `${toRepoPath(manifestPath)}: stale or missing template hash for convex/${relPath}`,
      )
    }
  }
}

if (violations.length > 0) {
  console.error('Convex generated setup drift check failed:')
  for (const violation of violations) console.error(`  - ${violation}`)
  process.exit(1)
}

console.log('Convex generated setup drift check passed.')
